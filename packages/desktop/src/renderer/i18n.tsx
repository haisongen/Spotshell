type TranslationKey = keyof typeof en
type TranslationParams = Record<string, string | number>

interface LanguageContextValue {
  language: AppLanguage
  t: (key: TranslationKey, params?: TranslationParams) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }): JSX.Element {
  const [language, setLanguage] = useState<AppLanguage>('en')

  useEffect(() => {
    let cancelled = false
    window.spotshell.getSettings().then((settings) => {
      if (!cancelled) setLanguage(settings.language)
    })
    const unsubscribe = window.spotshell.onLanguageChanged(setLanguage)
    return () => {
      cancelled = true
      unsubscribe()
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const t = useCallback(
    (key: TranslationKey, params?: TranslationParams): string => {
      const dictionary = language === 'zh-CN' ? zhCN : en
      const template = dictionary[key]
      if (!params) return template
      return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(params[name] ?? ''))
    },
    [language]
  )

  const value = useMemo(() => ({ language, t }), [language, t])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useTranslation(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useTranslation must be used within LanguageProvider')
  return context
}
